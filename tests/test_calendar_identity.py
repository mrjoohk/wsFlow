class IdentityFixture(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory(prefix='wsflow-P045-uid-');self.addCleanup(self.temp.cleanup)
        self.base=Path(self.temp.name);self.root=self.base/'root';self.root.mkdir()
        self.checkout=self.root/'project';self.checkout.mkdir();self.registry=self.root/'projects.json'
        self.projects=[{'id':'p','path':str(self.checkout)}]
        self.write(self.registry,{'roots':[{'path':str(self.root)}],'projects':self.projects})
        patch=mock.patch.dict(os.environ,{'WSFLOW_DATA_DIR':str(self.base/'data')});patch.start();self.addCleanup(patch.stop)
        self.local=calendar_store.Store(self.registry);self.managed()

    def write(self,path,value):
        path.parent.mkdir(parents=True,exist_ok=True);path.write_text(json.dumps(value),encoding='utf-8')

    def managed(self, project_uid='project-1', root_uid='root-1'):
        self.write(self.root/'.wsflow/workspace.json',{'schema_version':1,'root_uid':root_uid,'root_path':str(self.root)})
        self.write(self.checkout/'.wsflow/project.json',{'schema_version':1,'project_uid':project_uid,'root_uid':root_uid,'checkout_path':str(self.checkout)})

    def payload(self, kind='event', **extra):
        return ({'title':'original','body':'preserved body','location':'room','all_day':True,'start_date':'2026-10-17','end_date':'2026-10-18','project_ids':['p']}
                if kind=='event' else {'date':'2026-10-17','body':'preserved note','project_ids':['p']}) | extra

    def plan(self, kind='event', record=None, **extra):
        request={'kind':kind,'action':'update' if record else 'create','payload':self.payload(kind)}
        if record:request.update(id=record['id'],expected_revision=record['revision'])
        request.update(extra);return self.local.preview(request,self.projects)

    def apply(self, plan):return self.local.apply(plan['plan_id'],plan['operation_id'],self.projects)
    def create(self,kind='event'):return self.apply(self.plan(kind))['record']
    def query(self, **extra):return calendar_view.query(self.projects,self.local,'2026-10-17','2026-10-18',source_ids=['local'],**extra)
    def day(self,**extra):return self.query(**extra)['days'][0]
    def logical(self):
        if not self.local.path.exists():return None
        with closing(sqlite3.connect(self.local.path)) as db:return list(db.iterdump())
    def stored(self,record):
        with self.local.connection(True) as db:db.execute('UPDATE calendar_records SET data=? WHERE id=?',(operations.encoded(record),record['id']))


